'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
test('cookies, strict origin, five-attempt account/client limits, trusted proxy only', () => {
  const s = require('../auth-security');
  assert.throws(() => s.config({ NODE_ENV: 'production', PUBLIC_ORIGIN: 'https://sipeka.example' }), /REQUIRE_OWNER_2FA/);
  const optional = s.config({ NODE_ENV: 'production', PUBLIC_ORIGIN: 'https://sipeka.example', REQUIRE_OWNER_2FA: '0' });
  assert.equal(optional.requireOwner2FA, false);
  assert.match(s.cookie('abc', optional), /HttpOnly; SameSite=Strict; Secure/);
  const cfg = s.config({ NODE_ENV: 'production', PUBLIC_ORIGIN: 'https://sipeka.example', REQUIRE_OWNER_2FA: '1', TRUSTED_PROXY_IPS: '127.0.0.1', ALLOW_PRIVATE_QA_BEARER: '1' });
  assert.equal(s.validOrigin({ headers: { host: 'evil.example', origin: 'https://sipeka.example', 'x-forwarded-host': 'sipeka.example' } }, cfg), false);
  const privateQA = s.config({ NODE_ENV: 'test', ALLOW_PRIVATE_QA_BEARER: '1' });
  assert.equal(s.sessionToken({ headers: { authorization: 'Bearer qa' } }, privateQA), 'qa');
  assert.equal(s.sessionToken({ headers: { authorization: 'Bearer qa' } }, s.config({ NODE_ENV: 'test' })), null);
  const req = { headers: { host: 'sipeka.example', origin: 'https://sipeka.example', cookie: 'sipeka_session=abc', authorization: 'Bearer wrong', 'x-forwarded-for': '198.51.100.10' }, socket: { remoteAddress: '127.0.0.1' } };
  assert.equal(s.sessionToken(req, cfg), 'abc');
  assert.equal(s.sessionToken({ ...req, headers: { authorization: 'Bearer wrong' } }, cfg), null);
  assert.match(s.cookie('abc', cfg), /HttpOnly; SameSite=Strict; Secure/);
  assert.equal(s.validOrigin(req, cfg), true);
  assert.equal(s.validOrigin({ ...req, headers: { ...req.headers, origin: 'https://evil.example' } }, cfg), false);
  assert.equal(s.validOrigin({ ...req, headers: { ...req.headers, origin: undefined } }, cfg), false);
  assert.equal(s.clientIP(req, cfg), '198.51.100.10');
  assert.equal(s.clientIP({ ...req, socket: { remoteAddress: '198.51.100.20' } }, cfg), '198.51.100.20');
  const limiter = s.createLimiter(1000);
  for (let i = 0; i < 5; i++) assert.equal(limiter.blocked('owner', 'ip1', 0), false);
  assert.equal(limiter.blocked('owner', 'ip2', 0), true);
  assert.equal(limiter.blocked('different', 'ip1', 0), true);
  assert.equal(limiter.blocked('owner', 'ip1', 1001), false);
  limiter.reset('owner', 'ip1');
  for (let i = 0; i < 5; i++) assert.equal(limiter.blocked('owner', 'ip1', 1002), false);
});
test('TOTP uses server-generated encrypted secrets, validates current counter, rejects replay, hashes recovery codes', () => {
  const s = require('../auth-security');
  const key = crypto.randomBytes(32).toString('hex');
  const enrollment = s.newEnrollment('fixtureowner', key);
  assert.match(enrollment.uri, /^otpauth:\/\/totp\//);
  assert.ok(!enrollment.cipher.includes(enrollment.secret));
  assert.equal(s.decryptSecret(enrollment.cipher, key), enrollment.secret);
  const totp = s.totp(enrollment.secret, 'fixtureowner');
  const now = Date.now(), code = totp.generate({ timestamp: now });
  const counter = s.verifyTotp(enrollment.cipher, key, code, -1, now);
  assert.ok(counter > 0);
  assert.equal(s.verifyTotp(enrollment.cipher, key, code, counter, now), null);
  assert.equal(s.verifyTotp(enrollment.cipher, key, 'invalid', -1, now), null);
  const recovery = s.newRecoveryCodes();
  assert.equal(recovery.codes.length, 8);
  assert.equal(recovery.hashes.includes(recovery.codes[0]), false);
  assert.equal(s.recoveryHash(recovery.codes[0]), recovery.hashes[0]);
});
test('new passwords use Argon2id; valid legacy scrypt login requests rehash without resetting password', async () => {
  const security = require('../auth-security');
  const password = crypto.randomBytes(16).toString('hex');
  const hashed = await security.hashVerifiedPassword(password); // Existing lowercase credentials remain valid; new policy covered separately.
  assert.match(hashed, /^\$argon2id\$/);
  assert.deepEqual(await security.checkPassword(password, hashed), { valid: true, rehash: false });
  assert.equal((await security.checkPassword('incorrect', hashed)).valid, false);
  const salt = crypto.randomBytes(16).toString('hex');
  const legacy = salt + ':' + crypto.scryptSync(password, salt, 64).toString('hex');
  assert.deepEqual(await security.checkPassword(password, legacy), { valid: true, rehash: true });
  assert.equal((await security.checkPassword('incorrect', legacy)).valid, false);
  assert.equal((await security.checkPassword(password, 'malformed')).valid, false);
  await assert.rejects(security.hashNewPassword('short'), /6/);
});
