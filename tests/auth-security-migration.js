'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
test('migration 002 flags existing Owner, preserves hashes, revokes legacy sessions; missing auth columns block readiness', { skip: !process.env.DATABASE_URL, timeout: 30000 }, async t => {
  const { Pool } = require('pg');
  const admin = new Pool({ connectionString: process.env.DATABASE_URL });
  const schema = 'auth_migration_' + crypto.randomBytes(8).toString('hex');
  const url = new URL(process.env.DATABASE_URL); url.searchParams.set('options', '-c search_path=' + schema);
  const pool = new Pool({ connectionString: url.toString() });
  t.after(async () => { await pool.end(); await admin.query('DROP SCHEMA "' + schema + '" CASCADE'); await admin.end(); });
  await admin.query('CREATE SCHEMA "' + schema + '"');
  const name = fs.readdirSync(path.join(__dirname, '../migrations')).find(x => x.startsWith('001_') && x.endsWith('.sql'));
  const sql = fs.readFileSync(path.join(__dirname, '../migrations', name), 'utf8');
  await pool.query(sql);
  await pool.query('CREATE TABLE schema_migrations(name text PRIMARY KEY,sha256 text NOT NULL)');
  await pool.query('INSERT INTO schema_migrations(name,sha256) VALUES($1,$2)', [name, crypto.createHash('sha256').update(sql).digest('hex')]);
  const password = crypto.randomBytes(8).toString('hex'), salt = crypto.randomBytes(16).toString('hex');
  const hash = salt + ':' + crypto.scryptSync(password, salt, 64).toString('hex');
  await pool.query("INSERT INTO app_users(id,username,password_hash,full_name,role) VALUES('M_OWNER','mowner',$1,'Migration Owner','OWNER'),('M_STAFF','mstaff',$1,'Migration Staff','STAFF')", [hash]);
  await pool.query("INSERT INTO sessions(token,user_id,expired_at) VALUES('legacy','M_OWNER',(clock_timestamp() AT TIME ZONE 'UTC')+interval '1 hour')");
  const runner = require('../migrations/runner'); await runner.migrate(pool); await runner.verifySchema(pool);
  const users = (await pool.query('SELECT role,password_hash,password_change_required FROM app_users ORDER BY role')).rows;
  assert.equal(users.find(u => u.role === 'OWNER').password_change_required, true);
  assert.equal(users.find(u => u.role === 'STAFF').password_change_required, false);
  for (const user of users) assert.equal(user.password_hash, hash, 'no reset/rehash until valid login');
  assert.equal((await pool.query('SELECT token FROM sessions')).rowCount, 0);
  assert.equal((await pool.query('SELECT name FROM schema_migrations')).rowCount, 2);
  await pool.query('ALTER TABLE sessions DROP COLUMN last_seen_at');
  const { spawn } = require('node:child_process');
  const child = spawn(process.execPath, ['server.js'], { cwd: path.resolve(__dirname, '..'), env: { ...process.env, DATABASE_URL: url.toString(), NODE_ENV: 'test', REQUIRE_OWNER_2FA: '0' }, stdio: 'ignore' });
  const code = await new Promise(resolve => child.once('exit', resolve));
  assert.equal(code, 1, 'missing migration 002 column must block server listen');
});
